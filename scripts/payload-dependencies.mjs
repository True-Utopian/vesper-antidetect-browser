import assert from 'node:assert/strict';
import { cp, lstat, mkdtemp, readFile, realpath, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative, isAbsolute } from 'node:path';
import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';

const browser = 'node_modules/@true-utopian/vesper-browser';
export function payloadLock(source, metadata) {
  assert.ok(source.lockfileVersion >= 2 && source.packages?.[''], 'A current source dependency lock is required');
  const seed = structuredClone(source);
  seed.name = metadata.name; seed.version = metadata.version;
  seed.packages[''] = { name: metadata.name, version: metadata.version, license: metadata.license, dependencies: metadata.dependencies, ...(metadata.overrides ? { overrides: metadata.overrides } : {}) };
  // npm otherwise retains the old dependency snapshot of a local file package
  // even when its source changes without another application version bump.
  for (const name of Object.keys(seed.packages)) if (name === 'packages/vesper-browser' || name.startsWith('packages/vesper-browser/') || name === browser || name.startsWith(browser + '/')) delete seed.packages[name];
  delete seed.dependencies; // v2 legacy mirror is regenerated by npm.
  return seed;
}
function within(root, file) { const child = relative(root, file); assert.ok(child && !child.startsWith('..') && !isAbsolute(child), 'Dependency staging escaped its payload'); }
async function info(file) { try { return await lstat(file); } catch (e) { if (e.code === 'ENOENT') return undefined; throw e; } }
async function npm(cwd, args, npmCache) {
  await new Promise((done, reject) => {
    const env = npmCache ? { ...Object.fromEntries(Object.entries(process.env).filter(([key]) => key.toLowerCase() !== 'npm_config_cache')), npm_config_cache: npmCache } : process.env;
    const child = spawn(process.platform === 'win32' ? 'npm.cmd' : 'npm', args, { cwd, env, stdio: 'inherit', shell: process.platform === 'win32', windowsHide: true });
    child.once('error', reject); child.once('exit', code => code === 0 ? done() : reject(Error('Production dependency installation failed (' + code + ')')));
  });
}
export async function installPayloadDependencies({ root, payload, metadata, npmCache }) {
  root = await realpath(root); payload = await realpath(payload);
  assert.match(metadata.name, /^@true-utopian\/vesper-(browser|workbench)$/);
  assert.equal(metadata.dependencies['@true-utopian/vesper-browser'], 'file:packages/vesper-browser');
  const parent = dirname(payload), stage = await mkdtemp(join(parent, '.payload-dependencies-'));
  const previous = join(parent, '.payload-previous-node-modules-' + randomUUID());
  const pendingLock = join(parent, '.payload-lock-' + randomUUID());
  let oldMoved = false, newMoved = false;
  try {
    await cp(join(payload, 'packages/vesper-browser'), join(stage, 'packages/vesper-browser'), { recursive: true, filter: file => !file.split(/[\\/]/).includes('node_modules') });
    await writeFile(join(stage, 'package.json'), JSON.stringify(metadata, null, 2));
    const seed = payloadLock(JSON.parse(await readFile(join(root, 'package-lock.json'), 'utf8')), metadata);
    await writeFile(join(stage, 'package-lock.json'), JSON.stringify(seed, null, 2));
    await npm(stage, ['install', '--package-lock-only', '--install-links', '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund'], npmCache);
    await npm(stage, ['ci', '--install-links', '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund'], npmCache);
    const source = JSON.parse(await readFile(join(payload, 'packages/vesper-browser/package.json'), 'utf8'));
    const installed = JSON.parse(await readFile(join(stage, browser, 'package.json'), 'utf8'));
    for (const key of ['name', 'version', 'dependencies', 'exports', 'files']) assert.deepEqual(installed[key], source[key], 'Stale local Browser dependency snapshot: ' + key);
    await writeFile(pendingLock, await readFile(join(stage, 'package-lock.json')), { flag: 'wx' });
    const destination = join(payload, 'node_modules'), old = await info(destination);
    if (old) { assert.ok(old.isDirectory() && !old.isSymbolicLink(), 'Payload dependencies must be an ordinary generated directory'); await rename(destination, previous); oldMoved = true; }
    await rename(join(stage, 'node_modules'), destination); newMoved = true;
    await rename(pendingLock, join(payload, 'package-lock.json'));
    if (oldMoved) { within(parent, previous); await rm(previous, { recursive: true }); oldMoved = false; }
  } catch (error) {
    if (newMoved && await info(pendingLock)) { await rename(join(payload, 'node_modules'), join(stage, 'node_modules')); newMoved = false; }
    if (oldMoved && !newMoved) { await rename(previous, join(payload, 'node_modules')); oldMoved = false; }
    throw error;
  } finally {
    within(parent, stage); assert.ok((await lstat(stage)).isDirectory() && !(await lstat(stage)).isSymbolicLink());
    await rm(stage, { recursive: true });
    if (await info(pendingLock)) { within(parent, pendingLock); await rm(pendingLock); }
  }
}
